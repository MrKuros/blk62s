import { describe, expect, it } from 'vitest'
import {
  band,
  coverage,
  type FirmDayInput,
  firmHours,
  planGWh,
  reliabilityCurve,
  RISK_PRESETS,
  riskFromCosts,
} from './firm'

// q[i] = P(i+1) of actual/corrected; a linear grid from 0.51 to 1.49 keeps the arithmetic readable.
const Q = Array.from({ length: 99 }, (_, i) => 0.5 + (i + 1) / 100)

const day = (d: string, corrected: (number | null)[], actual: (number | null)[], q: number[] | null = Q) => ({
  day: d,
  calibrating: q === null,
  raw: corrected.map((c) => (c == null ? null : c + 1000)),
  corrected,
  actual,
  q,
})

describe('firm wind', () => {
  it('scales the corrected forecast by the r-th percentile, floored at zero', () => {
    expect(firmHours([10000, null, -100], Q, 10)).toEqual([6000, null, 0])
    const lower = firmHours([10000], Q, RISK_PRESETS['1in20'])[0]!
    const higher = firmHours([10000], Q, RISK_PRESETS['1in10'])[0]!
    expect(lower).toBeLessThan(higher)
    expect(higher).toBeLessThan(firmHours([10000], Q, RISK_PRESETS.balanced)[0]!)
  })

  it('builds a symmetric percentile band that collapses at r = 50', () => {
    const [b] = band([10000], Q, 10)
    expect(b!.lo).toBeCloseTo(6000)
    expect(b!.hi).toBeCloseTo(14000)
    const [m] = band([10000], Q, 50)
    expect(m!.lo).toBe(m!.hi)
    expect(band([null], Q, 10)).toEqual([{ lo: null, hi: null }])
  })

  it('rejects r outside the grid', () => {
    expect(() => firmHours([1], Q, 0)).toThrow(RangeError)
    expect(() => firmHours([1], Q, 100)).toThrow(RangeError)
  })

  it('counts hours, whole days, shortfall and firm share', () => {
    // r = 10 -> firm = 0.6 * corrected = 6000.
    const days = [
      day('2026-01-10', [10000, 10000], [7000, 6000]), // covered (equal counts as covered)
      day('2026-01-11', [10000, 10000], [5000, 9000]), // one hour 1000 MW short
      day('2026-01-12', [10000, null], [8000, 9000]), // second hour has no forecast: skipped
      day('2026-01-13', [10000], [1], null), // calibrating: left out
    ]
    const c = coverage(days, 10)
    expect(c.nHours).toBe(5)
    expect(c.hourCov).toBeCloseTo(4 / 5)
    expect(c.nDays).toBe(3)
    expect(c.dayCov).toBeCloseTo(2 / 3)
    expect(c.shortfallDays).toBe(1)
    expect(c.shortfallGWh).toBeCloseTo(1)
    expect(c.firmPct).toBeCloseTo((5 * 6000) / (5 * 11000))

    const ex = coverage(days, 10, { exclude: ['2026-01-11'] })
    expect(ex.nDays).toBe(2)
    expect(ex.hourCov).toBe(1)
  })

  it('reports NaN, not 0, when nothing is scored', () => {
    const c = coverage([day('2026-01-02', [1], [1], null)], 10)
    expect(c.nHours).toBe(0)
    expect(c.hourCov).toBeNaN()
  })

  it('traces reliability from 50% to 99% and never falls as the target rises', () => {
    const days = Array.from({ length: 20 }, (_, i) =>
      day(`2026-01-${String(i + 2).padStart(2, '0')}`, [10000, 10000], [5000 + i * 400, 15000 - i * 400]),
    )
    const { hour, day: whole } = reliabilityCurve(days)
    expect(hour).toHaveLength(50)
    expect(hour[0]!.target).toBeCloseTo(0.5)
    expect(hour.at(-1)!.target).toBeCloseTo(0.99)
    for (let i = 1; i < hour.length; i++) {
      expect(hour[i]!.achieved).toBeGreaterThanOrEqual(hour[i - 1]!.achieved)
      expect(whole[i]!.achieved).toBeLessThanOrEqual(hour[i]!.achieved)
    }
  })

  it('turns costs into a shortfall risk', () => {
    expect(riskFromCosts(9, 1)).toBe(10)
    expect(riskFromCosts(1, 1)).toBe(50)
    expect(riskFromCosts(1, 9)).toBe(50) // capped: never plan to be short more often than not
    expect(riskFromCosts(1000, 1)).toBe(1)
    expect(riskFromCosts(0, 0)).toBe(RISK_PRESETS.balanced)
  })

  it('sums the plan beyond wind in GWh', () => {
    expect(planGWh([10000, 12000, null], [6000, 7000, 5000])).toBeCloseTo(9)
  })
})

// Generated by the backend golden test (`UPDATE_GOLDEN=1 uv run pytest tests/test_golden.py`) from the same
// Python functions the API uses. Shape: { days: FirmDay[], cases: [{ r, exclude, coverage: <analysis.coverage> }],
// payload: the same for the rounded /firm payload the page actually receives, at the risk presets }.
interface ParityCase {
  r: number
  exclude: string[]
  coverage: Record<'hour_cov' | 'day_cov' | 'shortfall_gwh' | 'firm_pct', number> &
    Record<'n_hours' | 'n_days', number>
}
const parity = Object.values(
  import.meta.glob<{ days: FirmDayInput[]; cases: ParityCase[]; payload: { days: FirmDayInput[]; cases: ParityCase[] } }>(
    './firm_parity.json',
    {
      eager: true,
      import: 'default',
    },
  ),
)[0]

describe('parity with the Python implementation', () => {
  it.skipIf(!parity)(
    parity ? 'matches analysis.coverage within 1e-9' : 'SKIPPED: src/lib/firm_parity.json not generated yet',
    () => {
      expect(parity!.cases.length).toBeGreaterThan(0)
      for (const { r, exclude, coverage: py } of parity!.cases) {
        const js = coverage(parity!.days, r, { exclude })
        expect(js.nHours, `n_hours r=${r}`).toBe(py.n_hours)
        expect(js.nDays, `n_days r=${r}`).toBe(py.n_days)
        expect(Math.abs(js.hourCov - py.hour_cov), `hour_cov r=${r}`).toBeLessThan(1e-9)
        expect(Math.abs(js.dayCov - py.day_cov), `day_cov r=${r}`).toBeLessThan(1e-9)
        expect(Math.abs(js.shortfallGWh - py.shortfall_gwh), `shortfall_gwh r=${r}`).toBeLessThan(1e-9)
        expect(Math.abs(js.firmPct - py.firm_pct), `firm_pct r=${r}`).toBeLessThan(1e-9)
      }
    },
  )

  // MW arrive as integers and q to 4 dp, so an hour sitting exactly on its firm level can flip either way.
  it.skipIf(!parity)('matches the server on the rounded /firm payload to within one hour or day', () => {
    for (const { r, coverage: py } of parity!.payload.cases) {
      const js = coverage(parity!.payload.days, r)
      expect(js.nHours, `n_hours r=${r}`).toBe(py.n_hours)
      expect(js.nDays, `n_days r=${r}`).toBe(py.n_days)
      expect(Math.abs(js.hourCov - py.hour_cov) * py.n_hours, `hour_cov r=${r}`).toBeLessThanOrEqual(1 + 1e-9)
      expect(Math.abs(js.dayCov - py.day_cov) * py.n_days, `day_cov r=${r}`).toBeLessThanOrEqual(1 + 1e-9)
    }
  })
})
